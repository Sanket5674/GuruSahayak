import 'package:csv/csv.dart';
import 'package:share_plus/share_plus.dart';
import '../models/student.dart';
import '../models/school_asset.dart';
import '../models/mdm_record.dart';

class ExportService {
  // Generates UDISE+ / SARAL Student Profile CSV
  static String generateUdiseCsv(List<Student> students) {
    List<List<dynamic>> rows = [
      [
        'GR Number',
        'Roll No',
        'Student Name (School Register)',
        'Aadhaar Name',
        'Aadhaar Number',
        'APAAR ID',
        'PEN Number',
        'DOB',
        'Gender',
        'Standard',
        'Section',
        'Parent Name',
        'Parent Phone',
        'Bank Account',
        'IFSC Code',
        'Aadhaar Verified',
      ]
    ];

    for (var s in students) {
      rows.add([
        s.grNumber,
        s.rollNumber,
        s.nameInSchool,
        s.nameInAadhaar,
        s.aadhaarNo,
        s.apaarId,
        s.penNumber,
        s.dob,
        s.gender,
        s.standard,
        s.section,
        s.parentName,
        s.parentPhone,
        s.bankAccount,
        s.ifscCode,
        s.isAadhaarVerified ? 'YES' : 'NO',
      ]);
    }

    return const ListToCsvConverter().convert(rows);
  }

  // Generates School Infrastructure & Assets CSV
  static String generateAssetsCsv(List<SchoolAsset> assets) {
    List<List<dynamic>> rows = [
      ['Asset ID', 'Item Name', 'Category', 'Quantity', 'Condition Status', 'Funding Scheme', 'Location', 'Purchase Year', 'Remarks']
    ];

    for (var a in assets) {
      rows.add([
        a.id,
        a.name,
        a.category,
        a.quantity,
        a.condition.name.toUpperCase(),
        a.fundingScheme,
        a.location,
        a.purchaseYear,
        a.remarks,
      ]);
    }

    return const ListToCsvConverter().convert(rows);
  }

