  }

  // Generates Ad-Hoc Survey Responses CSV
  static String generateFormResponsesCsv(String formTitle, List<Map<String, dynamic>> records) {
    if (records.isEmpty) return 'No responses recorded.';
    final headers = records.first.keys.toList();
    List<List<dynamic>> rows = [headers];
    for (var r in records) {
      rows.add(headers.map((h) => r[h] ?? '').toList());
    }
    return const ListToCsvConverter().convert(rows);
  }

  static Future<void> shareTextContent(String content, String subject) async {
    await Share.share(content, subject: subject);
  }
}

